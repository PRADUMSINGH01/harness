// Builds the creative asset library: harness/assets/creative/<folder>/<stem>.svg plus a per-folder
// index.json the catalog reads (kind, tags, description, usage), a README and a preview contact sheet.
// Deterministic: rerunning produces identical files.   node scripts/creative-assets/build.mjs
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { THEME } from "./lib.mjs";
import backgrounds from "./backgrounds.mjs";
import overlays from "./overlays.mjs";
import shapes from "./shapes.mjs";
import doodles from "./doodles.mjs";
import mockups from "./mockups.mjs";
import charts from "./charts.mjs";
import titles from "./titles.mjs";
import mattes from "./mattes.mjs";
import icons from "./icons.mjs";
import frames from "./frames.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "..", "..", "assets", "creative");

const CATEGORIES = [
  ["backgrounds", "Backgrounds", "Full-frame grounds every scene sits on.", backgrounds],
  ["overlays", "Overlays", "Full-frame blend layers over a finished scene: grain, leaks, flares, letterbox.", overlays],
  ["shapes", "Shapes", "Organic and geometric decoration, soft-3D objects, glass.", shapes],
  ["doodles", "Doodles", "Hand-drawn annotations that draw themselves on.", doodles],
  ["mockups", "Mockups", "Device frames, windows, cursors and generic UI pieces for product films.", mockups],
  ["charts", "Charts", "Data-viz templates with animatable bars, lines, rings and counters.", charts],
  ["titles", "Titles", "Lower thirds, callouts, labels, badges and chapter cards.", titles],
  ["mattes", "Mattes", "Transition shapes: wipes, irises, brush and ink reveals.", mattes],
  ["icons", "Icons", "One consistent line-icon set (24-unit grid, 1.8 stroke).", icons],
  ["frames", "Frames", "Borders and containers with real openings: film, polaroid, stamp, viewfinder.", frames],
];

const problems = [];
let total = 0;
rmSync(OUT, { recursive: true, force: true });

const preview = [];
for (const [folder, label, blurb, assets] of CATEGORIES) {
  const dir = join(OUT, folder);
  mkdirSync(dir, { recursive: true });
  const seen = new Set();
  const items = [];
  for (const a of assets) {
    if (seen.has(a.stem)) problems.push(`${folder}/${a.stem}: duplicate stem`);
    seen.add(a.stem);
    const idPrefix = `cx-${folder.slice(0, 3)}-${a.stem}`;
    const markup = a.svg(idPrefix);
    for (const bad of ["undefined", "NaN", "Infinity", "[object"]) if (markup.includes(bad)) problems.push(`${folder}/${a.stem}: contains ${bad}`);
    for (const m of markup.matchAll(/\bid="([^"]+)"/g)) {
      if (/^cx-/.test(m[1]) && !m[1].startsWith(idPrefix)) problems.push(`${folder}/${a.stem}: foreign def id ${m[1]}`);
    }
    for (const m of markup.matchAll(/url\(#([^)]+)\)/g)) {
      if (!markup.includes(`id="${m[1]}"`)) problems.push(`${folder}/${a.stem}: url(#${m[1]}) has no definition`);
    }
    if (/\s(fill|stroke)="var\(/.test(markup)) problems.push(`${folder}/${a.stem}: var() in a presentation attribute`);
    const bytes = Buffer.byteLength(markup);
    writeFileSync(join(dir, `${a.stem}.svg`), markup);
    items.push({
      id: a.stem,
      name: a.name,
      type: "svg",
      kind: a.kind,
      src: `assets/creative/${folder}/${a.stem}.svg`,
      format: "svg",
      width: a.w,
      height: a.h,
      tags: [...new Set([...a.tags, a.kind, "creative"])],
      description: a.description,
      ...(a.usage_css ? { usage_css: a.usage_css } : {}),
      ...(a.animation ? { animation: a.animation } : {}),
      license: "original work generated by the harness (scripts/creative-assets); free to use",
      bytes,
    });
    preview.push({ folder, a, markup });
    total++;
  }
  writeFileSync(join(dir, "index.json"), `${JSON.stringify({ category: folder, label, description: blurb, items }, null, 2)}\n`);
}

// README: the theming and animation contract, plus the full catalog.
const readme = [
  "# Creative asset library",
  "",
  `${total} original, themeable SVG elements for HyperFrames videos, generated by \`scripts/creative-assets/build.mjs\` (rerun it to rebuild; output is deterministic). Agents find them with \`search_assets\` and copy them in with \`use_asset\`.`,
  "",
  "They follow what current short-form, motion-graphics and product-launch work is built from: hand-drawn annotations and paper/grain textures (the 'human, imperfect' 2026 look), soft 3D plus flat hybrids, UI mockups with cursor beats, lower thirds and callouts, data-viz templates, shape-wipe transitions and light leaks.",
  "",
  "## Theming",
  "",
  "Colors are CSS custom properties with fallbacks, so the defaults render as `<img>` and the brand palette applies when the SVG is **inlined** in a composition and the variables are set on an ancestor:",
  "",
  "| Variable | Role | Default |",
  "| --- | --- | --- |",
  ...Object.entries(THEME).map(([k, v]) => `| \`--${k}\` | ${{ ink: "primary lines and text", surface: "panels and grounds", accent: "brand highlight", "accent-2": "second highlight", "accent-3": "third highlight (success)", muted: "secondary text, grids", paper: "paper grounds", highlight: "marker yellow" }[k]} | \`${v}\` |`),
  "| `--font` | text in mockups and titles | Inter |",
  "",
  "```html",
  '<div style="--accent:#CF795D; --ink:#F1EADF; --surface:#171914; --font:Geist">',
  "  <!-- paste the SVG markup here -->",
  "</div>",
  "```",
  "",
  "## Animating",
  "",
  "- **Draw-on strokes** carry `class=\"draw\"`, `pathLength=\"1\"` and `stroke-dasharray: 1 1.05`. Tween `stroke-dashoffset` from `1.02` (hidden) to `0` (drawn). Doodles, icons, rings, rules and chart lines all support it.",
  "- **Named parts** (`#bar-1`, `#needle`, `#knob`, `.tile`, ...) are listed in each asset's description. Animate them individually; never loop an idle wobble.",
  "- **Copy** in mockups, titles and charts lives in `<text id=\"...\">` elements. Replace it with the brief's real words and numbers, never invented claims.",
  "- **Frames** have real transparent openings. Put the photo or screenshot behind the frame at the box given in the description.",
  "- **Mattes** are transition shapes: sweep or scale one over the cut (shape wipe), or use it as a CSS `mask-image`.",
  "- **Overlays** go over the finished scene with the `usage_css` blend mode and opacity in `index.json`.",
  "",
  "## Catalog",
  "",
  ...CATEGORIES.flatMap(([folder, label, blurb, assets]) => [
    `### ${label} (\`kind: ${assets[0].kind}\`, ${assets.length})`,
    "",
    blurb,
    "",
    "| id | name | size |",
    "| --- | --- | --- |",
    ...assets.map((a) => `| \`${folder}/${a.stem}\` | ${a.name} | ${a.w}×${a.h} |`),
    "",
  ]),
].join("\n");
writeFileSync(join(OUT, "README.md"), readme);

// Contact sheet: every asset inlined (so the theme applies) on a backdrop that suits its kind.
const backdrop = {
  overlay: "background:linear-gradient(135deg,#3b4a6b,#c08457)",
  matte: "background:#0B0C0E",
  background: "background:#000",
};
const sheet = `<!doctype html><html><head><meta charset="utf-8"><title>Creative assets</title>
<style>
body{margin:0;background:#0B0C0E;color:#EDEBE6;font:14px/1.4 Inter,system-ui,sans-serif;padding:24px}
h2{margin:32px 0 12px;font-size:20px} .grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:14px}
.card{background:#16181D;border:1px solid #262930;border-radius:12px;overflow:hidden}
.stage{height:190px;display:flex;align-items:center;justify-content:center;padding:12px;box-sizing:border-box;background:#111216}
.stage svg{max-width:100%;max-height:100%;width:auto;height:auto}
.meta{padding:8px 10px;border-top:1px solid #262930}.meta b{display:block;font-size:13px}.meta code{color:#8B8F98;font-size:12px}
</style></head><body>
<h1>Creative asset library: ${total} assets</h1>
${CATEGORIES.map(
  ([folder, label]) => `<h2 id="${folder}">${label}</h2><div class="grid">${preview
    .filter((p) => p.folder === folder)
    .map((p) => `<div class="card"><div class="stage" style="${backdrop[p.a.kind] ?? ""}">${p.markup.replace(/<svg /, `<svg width="100%" height="100%" `)}</div><div class="meta"><b>${p.a.name}</b><code>${folder}/${p.a.stem}</code></div></div>`)
    .join("")}</div>`,
).join("\n")}
</body></html>`;
writeFileSync(join(OUT, "preview.html"), sheet);

console.log(`${total} assets in ${CATEGORIES.length} folders -> ${OUT}`);
for (const [folder, , , assets] of CATEGORIES) console.log(`  ${folder.padEnd(12)} ${assets.length}`);
if (problems.length) {
  console.error(`\n${problems.length} problems:\n${problems.join("\n")}`);
  process.exit(1);
}
